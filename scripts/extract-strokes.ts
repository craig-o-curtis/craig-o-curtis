// Writes scripts/lib/strokes.ts: the strokes of every character the idioms use, in writing order, each as its
// outline and its median (the line the brush follows), for Simplified and for Traditional. Run it after adding
// an idiom with a new character:
//
//   curl -sLO https://raw.githubusercontent.com/parsimonhi/animCJK/master/graphicsZhHans.txt
//   curl -sLO https://raw.githubusercontent.com/parsimonhi/animCJK/master/graphicsZhHant.txt
//   curl -sLO https://raw.githubusercontent.com/skishore/makemeahanzi/master/graphics.txt
//   node scripts/extract-strokes.ts graphicsZhHans.txt graphicsZhHant.txt graphics.txt
//
// Where each character comes from, first match wins:
//   Simplified:  animCJK zh-Hans (mainland stroke order), then Make Me a Hanzi.
//   Traditional: animCJK zh-Hant (Taiwan stroke order), then animCJK zh-Hans for a character the two scripts
//                share, then Make Me a Hanzi.
//
// The data is derived from Arphic PL KaitiM GB and Big5 and is used under the Arphic Public License
// (https://ftp.gnu.org/non-gnu/chinese-fonts-truetype/LICENSE). animCJK: https://github.com/parsimonhi/animCJK.
// Make Me a Hanzi: https://github.com/skishore/makemeahanzi. Both draw in a 1024 box with y pointing up and the
// baseline at 900.

import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { IDIOMS, VARIANT_LABELS } from "./lib/idioms.ts";

interface Graphic {
  character: string;
  strokes: string[];
  medians: number[][][];
}

const OUT = path.join(path.dirname(fileURLToPath(import.meta.url)), "lib", "strokes.ts");
const [hansFile, hantFile, mmahFile] = process.argv.slice(2);
if (!hansFile || !hantFile || !mmahFile) throw new Error("usage: node scripts/extract-strokes.ts <graphicsZhHans.txt> <graphicsZhHant.txt> <graphics.txt>");

async function load(file: string): Promise<Map<string, Graphic>> {
  const lines = (await readFile(file, "utf8")).split("\n").filter(Boolean);
  return new Map(lines.map((l) => JSON.parse(l) as Graphic).map((g) => [g.character, g]));
}
const [hans, hant, mmah] = await Promise.all([load(hansFile), load(hantFile), load(mmahFile)]);

const median = (pts: number[][]) => `M${pts.map(([x, y]) => `${x} ${y}`).join("L")}`;
const entry = (ch: string, g: Graphic, from: string) =>
  `  "${ch}": { from: "${from}", strokes: ${JSON.stringify(g.strokes)}, medians: ${JSON.stringify(g.medians.map(median))} },`;

function pick(ch: string, order: Array<[string, Map<string, Graphic>]>): [Graphic, string] {
  for (const [name, set] of order) {
    const g = set.get(ch);
    if (g) return [g, name];
  }
  throw new Error(`no stroke data for ${ch}`);
}

const simplified = [...new Set([...IDIOMS.flatMap((i) => [...i.hanzi]), ...VARIANT_LABELS.simplified])].sort();
const traditional = [...new Set([...IDIOMS.flatMap((i) => [...i.traditional]), ...VARIANT_LABELS.traditional])].sort();

const sRows = simplified.map((ch) => entry(ch, ...pick(ch, [["animCJK zh-Hans", hans], ["Make Me a Hanzi", mmah]])));
// Traditional keeps only what differs from the Simplified entry; the renderer falls back to that.
const tRows = traditional.flatMap((ch) => {
  const [g, from] = pick(ch, [["animCJK zh-Hant", hant], ["animCJK zh-Hans", hans], ["Make Me a Hanzi", mmah]]);
  return simplified.includes(ch) && from === "animCJK zh-Hans" ? [] : [entry(ch, g, from)];
});

await writeFile(
  OUT,
  `// Generated by scripts/extract-strokes.ts from animCJK and Make Me a Hanzi (Arphic Public License): each
// character's strokes in writing order, as outlines and as the medians the brush follows, in a 1024 box with
// y up and the baseline at 900. Don't edit; re-run that script.

export interface Strokes {
  from: string;
  strokes: string[];
  medians: string[];
}

export const SIMPLIFIED: Record<string, Strokes> = {
${sRows.join("\n")}
};

/** Only the characters whose Traditional form or stroke order differs; anything else is in SIMPLIFIED. */
export const TRADITIONAL: Record<string, Strokes> = {
${tRows.join("\n")}
};
`,
);
console.log(`strokes.ts: ${sRows.length} simplified, ${tRows.length} traditional`);
