// Writes scripts/lib/hanzi.ts: the 16 × 16 bitmap of every character the idioms use, taken from a GNU Unifont
// .hex file. Run it after adding an idiom with a new character:
//
//   curl -sO https://unifoundry.com/pub/unifont/unifont-17.0.05/font-builds/unifont-17.0.05.hex.gz
//   gunzip unifont-17.0.05.hex.gz
//   node scripts/extract-hanzi.ts unifont-17.0.05.hex
//
// GNU Unifont is dual-licensed under the SIL Open Font License 1.1 and the GNU GPL 2+ with the font embedding
// exception; the glyphs are used here under the OFL. https://unifoundry.com/unifont/

import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { IDIOMS } from "./lib/idioms.ts";

const OUT = path.join(path.dirname(fileURLToPath(import.meta.url)), "lib", "hanzi.ts");
const [hexFile] = process.argv.slice(2);
if (!hexFile) throw new Error("usage: node scripts/extract-hanzi.ts <unifont.hex>");
const version = /unifont-([\d.]+)\.hex$/.exec(path.basename(hexFile))?.[1] ?? "unknown";

const font = new Map<number, string>();
for (const line of (await readFile(hexFile, "utf8")).split("\n")) {
  const [code, bits] = line.trim().split(":");
  if (code && bits) font.set(Number.parseInt(code, 16), bits);
}

const chars = [...new Set(IDIOMS.flatMap((i) => [...i.hanzi]))].sort();
const rows = chars.map((ch) => {
  const bits = font.get(ch.codePointAt(0)!);
  if (!bits || bits.length !== 64) throw new Error(`Unifont has no 16 × 16 glyph for ${ch}`);
  return `  "${ch}": "${bits}",`;
});

await writeFile(
  OUT,
  `// Generated by scripts/extract-hanzi.ts from GNU Unifont ${version} (unifoundry.com, SIL OFL 1.1): each character
// the idioms use, as 16 rows of 4 hex digits, the leftmost pixel in the high bit. Don't edit; re-run that script.

export const HANZI: Record<string, string> = {
${rows.join("\n")}
};
`,
);
console.log(`hanzi.ts: ${chars.length} characters`);
